/* OAones：日志保留设置。默认 0 = 永久保留，自动任务每天检查一次。 */
DECLARE
    v_cnt NUMBER;
BEGIN
    SELECT COUNT(1) INTO v_cnt FROM user_tables
     WHERE table_name = 'UF_OAONES_LOG_RETENTION';
    IF v_cnt = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE TABLE uf_oaones_log_retention (
                id                     NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
                log_code               VARCHAR2(64 CHAR) NOT NULL,
                keep_days              NUMBER(10) DEFAULT 0 NOT NULL,
                modedatacreater        NUMBER(10),
                modedatacreatedate     VARCHAR2(10 CHAR),
                modedatacreatetime     VARCHAR2(8 CHAR),
                modedatamodifier       NUMBER(10),
                modedatamodifydatetime VARCHAR2(100 CHAR),
                CONSTRAINT PK_UF_OAONES_LOG_RETENTION PRIMARY KEY (id),
                CONSTRAINT UK_OAONES_LOG_RETENTION_CODE UNIQUE (log_code)
            )';
        EXECUTE IMMEDIATE 'COMMENT ON TABLE uf_oaones_log_retention IS ''OAones 日志保留设置（<=0 永久保留）''';
        DBMS_OUTPUT.PUT_LINE('created uf_oaones_log_retention');
    ELSE
        DBMS_OUTPUT.PUT_LINE('uf_oaones_log_retention already exists');
    END IF;
END;
/


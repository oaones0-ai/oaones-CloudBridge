DECLARE
    v_cnt NUMBER;
BEGIN
    SELECT COUNT(1) INTO v_cnt FROM user_tables
     WHERE table_name = 'UF_OAONES_FEATURE_SETTING';
    IF v_cnt = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE TABLE uf_oaones_appsyn_feature_setting (
                id                     NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
                feature_code           VARCHAR2(80 CHAR) NOT NULL,
                enabled                NUMBER(1) DEFAULT 1 NOT NULL,
                modedatacreater        NUMBER(10),
                modedatacreatedate     VARCHAR2(10 CHAR),
                modedatacreatetime     VARCHAR2(8 CHAR),
                modedatamodifier       NUMBER(10),
                modedatamodifydatetime VARCHAR2(100 CHAR),
                CONSTRAINT PK_UF_OAONES_FEATURE_SETTING PRIMARY KEY (id),
                CONSTRAINT UK_OAONES_FEATURE_SETTING_CODE UNIQUE (feature_code)
            )';
        EXECUTE IMMEDIATE 'COMMENT ON TABLE uf_oaones_appsyn_feature_setting IS ''OAones 功能设置（1 启用 / 0 隐藏）''';
        DBMS_OUTPUT.PUT_LINE('created uf_oaones_appsyn_feature_setting');
    ELSE
        DBMS_OUTPUT.PUT_LINE('uf_oaones_appsyn_feature_setting already exists');
    END IF;
END;

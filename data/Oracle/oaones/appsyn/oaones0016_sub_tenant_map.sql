DECLARE
    v_cnt NUMBER;
BEGIN
    SELECT COUNT(1) INTO v_cnt FROM user_tables WHERE table_name = 'UF_OAONES_SUB_TENANT_MAP';
    IF v_cnt = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE TABLE uf_oaones_sub_tenant_map (
                id                     NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
                cfg_id                 NUMBER(10) NOT NULL,
                oa_sub_id              NUMBER(10) NOT NULL,
                type                   NUMBER(10) DEFAULT 0 NOT NULL,
                yx                     NUMBER(10) DEFAULT 0,
                remark                 VARCHAR2(300 CHAR),
                formmodeid             NUMBER(10),
                modedatacreater        NUMBER(10),
                modedatacreatedate     VARCHAR2(10 CHAR),
                modedatacreatetime     VARCHAR2(8 CHAR),
                modedatamodifier       NUMBER(10),
                modedatamodifydatetime VARCHAR2(100 CHAR),
                CONSTRAINT PK_UF_OAONES_SUB_TENANT_MAP PRIMARY KEY (id)
            )';
        EXECUTE IMMEDIATE 'CREATE UNIQUE INDEX UK_OAONES_SUB_TENANT_SUB
            ON uf_oaones_sub_tenant_map(type, oa_sub_id)';
        EXECUTE IMMEDIATE 'CREATE UNIQUE INDEX UK_OAONES_SUB_TENANT_CFG
            ON uf_oaones_sub_tenant_map(type, cfg_id)';
        EXECUTE IMMEDIATE 'CREATE INDEX IDX_OAONES_SUB_TENANT_CFG
            ON uf_oaones_sub_tenant_map(cfg_id)';
        EXECUTE IMMEDIATE 'COMMENT ON TABLE uf_oaones_sub_tenant_map IS ''OAones OA分部-平台租户一对一映射''';
        DBMS_OUTPUT.PUT_LINE('created uf_oaones_sub_tenant_map');
    ELSE
        DBMS_OUTPUT.PUT_LINE('uf_oaones_sub_tenant_map already exists');
    END IF;
END;
